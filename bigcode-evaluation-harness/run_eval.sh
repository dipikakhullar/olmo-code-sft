#!/bin/bash

# --- SLURM JOB SUBMISSION DIRECTIVES ---
# Revised for an evaluation-only job
#SBATCH --job-name=multipl-e-EVAL-ONLY
#SBATCH --nodes=1
#SBATCH --ntasks-per-node=1
#SBATCH --cpus-per-task=8        # Evaluation is less CPU intensive
#SBATCH --mem=64G                # Evaluation requires less RAM
#SBATCH --gpus-per-node=0        # <-- CHANGE: No GPUs needed for evaluation
#SBATCH --time=03:00:00          # Evaluation is much faster, 3 hours is very safe
#SBATCH --account=xlab
#SBATCH --partition=gpu-a100     # <-- CHANGE: Run on a CPU partition if available, otherwise keep gpu-a100

# --- SCRIPT SETUP ---
echo "--- Setting up the Environment ---"
set -e # Exit immediately if a command exits with a non-zero status.

# Define the directory where your JSON results are stored
JSON_INPUT_DIR="json_outputs"

# Navigate to the correct directory
# IMPORTANT: Make sure this path is correct
cd /mmfs1/home/seunguk/gscratch/bigcode-evaluation-harness

# Activate your Python virtual environment
source /mmfs1/home/seunguk/gscratch/bigcode-evaluation-harness/big-venv/bin/activate

# --- BENCHMARK EXECUTION ---
echo "--- Starting Evaluation-Only Run ---"

# Define the list of languages that you successfully generated
# This list is based on the files you provided
LANGS=(
    "cs" "d" "dart" "elixir" "go" "hs" "java" "jl" "js" "lua" "php"
    "r" "rb" "rkt" "rs" "scala" "sh" "swift" "ts"
)
# NOTE: "cpp" and "rust" were in your original LANGS list but not in the `ls` output.
# I have removed them. If they exist, you can add them back.

# Create a master log file for this evaluation run
LOG_FILE="evaluation_run_$(date +%Y-%m-%d_%H-%M-%S).log"
echo "Starting evaluation run at $(date)" | tee -a "${LOG_FILE}"

# Loop through each language
for lang in "${LANGS[@]}"; do
    echo "=============================================" | tee -a "${LOG_FILE}"
    echo "             STARTING EVALUATION: ${lang}" | tee -a "${LOG_FILE}"
    echo "=============================================" | tee -a "${LOG_FILE}"

    # Construct the EXACT filename that was generated by the previous script
    GEN_FILE="${JSON_INPUT_DIR}/generations_${lang}_full_13gpu_multiple-${lang}.json"

    # Check if the generation file actually exists before trying to evaluate it
    if [ ! -f "${GEN_FILE}" ]; then
        echo "!!! Generation file NOT FOUND for ${lang}: ${GEN_FILE}. Skipping. !!!" | tee -a "${LOG_FILE}"
        continue
    fi

    # --- EVALUATION STEP ONLY ---
    echo "--- Evaluating file: ${GEN_FILE} at $(date) ---" | tee -a "${LOG_FILE}"
    (
        SECONDS=0

        # Run the evaluation command inside the container
        apptainer exec \
            --pwd /app \
            --bind $(pwd):/app \
            --bind $HOME:$HOME \
            --bind /gscratch/stf/seunguk:/gscratch/stf/seunguk \
            evaluation-harness-multiple.sif \
            python3 main.py \
                --model allenai/OLMo-2-0425-1B-Instruct \
                --tasks "multiple-${lang}" \
                --n_samples 20 \
                --temperature 0.2 \
                --top_p 0.95 \
                --load_generations_path "${GEN_FILE}" \
                --allow_code_execution | tee -a "${LOG_FILE}"

        duration=$SECONDS
        echo "Evaluation for ${lang} finished in $(($duration / 60)) minutes and $(($duration % 60)) seconds." | tee -a "${LOG_FILE}"
    )

    echo "=============================================" | tee -a "${LOG_FILE}"
    echo "             FINISHED EVALUATION: ${lang}" | tee -a "${LOG_FILE}"
    echo "=============================================" | tee -a "${LOG_FILE}"
done

echo "--- All evaluations completed at $(date)! ---" | tee -a "${LOG_FILE}"
